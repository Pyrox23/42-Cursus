int	ft_iterative_power(int nb, int power);

int	ft_iterative_power(int nb, int power)
{
	int		result;

	if (nb == 0 && power == 0)
		return (1);
	if (power < 0)
		return (0);
	if (power == 0)
		return (1);
	result = nb;
	while (power > 1)
	{
		result *= nb;
		power--;
	}
	return (result);
}
