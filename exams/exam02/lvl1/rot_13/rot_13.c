#include <unistd.h>

int	main(int ac, char **av)
{
	int		i;
	char	c;

	if (ac != 2)
		return (write(1, "\n", 1), 0);
	i = -1;
	while (av[1][++i])
	{
		c = 0;
		if (av[1][i] <= 'z' && av[1][i] >= 'a')
			c = 'a' + (av[1][i] - 'a' + 13) % 26;
		else if (av[1][i] <= 'Z' && av[1][i] >= 'A')
			c = 'A' + (av[1][i] - 'A' + 13) % 26;
		else
			c = av[1][i];
		write(1, &c, 1);
	}
	write(1, "\n", 1);
	return (0);
}
