#include "libft.h"

char	*ft_strdup(const char *src)
{
	char			*dup;
	size_t			i;

	if (!src)
		return (NULL);
	i = 0;
	dup = (char *) ft_calloc(ft_strlen(src) + 1, sizeof(char));
	if (!dup)
		return (NULL);
	while (src[i])
	{
		dup[i] = src[i];
		i++;
	}
	dup[i] = 0;
	return (dup);
}
